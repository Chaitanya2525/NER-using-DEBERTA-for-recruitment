# Utility functions
def normalize_filename(filename: str) -> str:
    """Normalize filenames by removing spaces, underscores, parentheses, and numbers"""
    normalized = re.sub(r'\s*\(\d+\)|[\s_]+', '', filename.lower())
    logging.debug(f"Normalized filename: {filename} -> {normalized}")
    return normalized

def extract_text(pdf_content: bytes) -> str:
    """Extract text from PDF content and clean repeated letters"""
    try:
        with pdfplumber.open(BytesIO(pdf_content)) as pdf:
            text = "".join(page.extract_text() or "" for page in pdf.pages)
            if not text:
                logging.warning("No text extracted from PDF")
                return ""

            # Clean repeated letters (e.g., "CCaarreeeerr" -> "Career")
            cleaned_text = re.sub(r'(.)\1{2,}', r'\1', text)  # Replace 3+ repeated chars with single char
            cleaned_text = re.sub(r'(.)\1', r'\1', cleaned_text)  # Replace double chars with single char
            logging.info(f"Extracted and cleaned text from PDF: {len(cleaned_text)} characters")
            return cleaned_text
    except Exception as e:
        logging.error(f"Error processing PDF: {e}")
        return ""

