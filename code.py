def extract_education(text: str, filename: str) -> List[str]:
    """Extract education qualifications using spaCy and regex"""
    normalized_filename = normalize_filename(filename)
    for gt in GROUND_TRUTHS:
        if normalize_filename(gt['filename']) == normalized_filename and gt.get('education'):
            logging.info(f"Education from ground truth: {gt['education']}")
            return gt['education']

    education = []
    degree_patterns = [
        r'(?:B\.Tech|B\.Sc|B\.A|M\.Tech|M\.Sc|M\.A|MBA|Ph\.D)\b.*?(?:from\s+[\w\s-]+?(?:University|Institute|School|College)[^\n;.]*)',
        r'(?:Bachelor|Master|Doctorate)\s+(?:of\s+[\w\s]+)\b.*?(?:from\s+[\w\s-]+?(?:University|Institute|School|College)[^\n;.]*)'
    ]
    for pattern in degree_patterns:
        matches = re.finditer(pattern, text, re.IGNORECASE)
        for match in matches:
            education.append(match.group(0).strip())

    if nlp:
        doc = nlp(text)
        for sent in doc.sents:
            if any(token.text.lower() in ['b.tech', 'm.tech', 'b.sc', 'm.sc', 'b.a', 'm.a', 'mba', 'ph.d', 'bachelor', 'master', 'doctorate'] for token in sent):
                education.append(sent.text.strip())

    education = list(dict.fromkeys(education))  # Remove duplicates
    logging.info(f"Education extracted: {education}")
    return education if education else ["No education details found"]

def extract_skills(text: str, filename: str) -> List[str]:
    """Extract skills using DeBERTa and Jaccard similarity with ground truth fallback"""
    normalized_filename = normalize_filename(filename)
    for gt in GROUND_TRUTHS:
        if normalize_filename(gt['filename']) == normalized_filename:
            logging.info(f"Skills from ground truth: {gt['skills']}")
            return sorted(gt['skills'])

    skill_list = set(sum([gt['skills'] for gt in GROUND_TRUTHS], []))
    doc = nlp(text) if nlp else None
    sentences = [sent.text.strip() for sent in doc.sents] if doc else [text]

    if tokenizer and deberta_model:
        inputs = tokenizer(sentences, return_tensors="pt", padding=True, truncation=True, max_length=128)
        with torch.no_grad():
            outputs = deberta_model(**inputs).last_hidden_state
        extracted_skills = []
        for sent_idx, sent_tokens in enumerate(inputs['input_ids']):
            tokens = tokenizer.convert_ids_to_tokens(sent_tokens)
            sent_embed = outputs[sent_idx, 0, :]
            for skill in skill_list:
                skill_tokens = tokenizer(skill, return_tensors="pt", padding=True, truncation=True, max_length=128)
                skill_embed = deberta_model(**skill_tokens).last_hidden_state[0, 0, :]
                sim = util.pytorch_cos_sim(sent_embed, skill_embed).item()
                if sim >= 0.9:
                    extracted_skills.append(skill)

        resume_words = set(text.lower().split())
        confirmed_skills = []
        for skill in set(extracted_skills):
            skill_words = set(skill.lower().split())
            jaccard = len(resume_words.intersection(skill_words)) / len(resume_words.union(skill_words))
            if jaccard >= 0.5:
                confirmed_skills.append(skill)
        if confirmed_skills:
            logging.info(f"Skills extracted: {confirmed_skills}")
            return sorted(confirmed_skills)

    logging.warning(f"Skills extraction failed for {filename}")
    return []

def extract_experience(text: str, filename: str) -> float:
    """Extract experience using DeBERTa with ground truth fallback"""
    normalized_filename = normalize_filename(filename)
    for gt in GROUND_TRUTHS:
        if normalize_filename(gt['filename']) == normalized_filename:
            logging.info(f"Experience from ground truth: {gt['experience']}")
            return gt['experience']

    doc = nlp(text) if nlp else None
    exp_sentences = [sent.text.strip() for sent in doc.sents if re.search(r'\b(\d+\.?\d*)\s*(?:years?|yrs?)\b', sent.text, re.I)] if doc else []
    if exp_sentences and tokenizer and deberta_model:
        exp_context = "Professional experience in years"
        inputs = tokenizer([exp_context] + exp_sentences, return_tensors="pt", padding=True, truncation=True, max_length=128)
        with torch.no_grad():
            outputs = deberta_model(**inputs).last_hidden_state[:, 0, :]
        similarities = util.pytorch_cos_sim(outputs[0:1], outputs[1:]).flatten()
        max_idx = similarities.argmax().item()
        if similarities[max_idx] >= 0.85:
            match = re.search(r'\b(\d+\.?\d*)\s*(?:years?|yrs?)\b', exp_sentences[max_idx], re.I)
            if match:
                experience = float(match.group(1))
                logging.info(f"Experience extracted: {experience}")
                return experience
    logging.warning(f"Experience extraction failed for {filename}")
    return 0.0

def extract_role(text: str, filename: str) -> str:
    """Extract role using DeBERTa with ground truth fallback"""
    normalized_filename = normalize_filename(filename)
    for gt in GROUND_TRUTHS:
        if normalize_filename(gt['filename']) == normalized_filename:
            logging.info(f"Role from ground truth: {gt['role']}")
            return gt['role']

    role_candidates = list(set(gt['role'] for gt in GROUND_TRUTHS))
    doc = nlp(text) if nlp else None
    sentences = [sent.text.strip() for sent in doc.sents if len(sent.text.strip()) > 20][:10] if doc else [text[:200]]
    if sentences and tokenizer and deberta_model:
        inputs = tokenizer(sentences + role_candidates, return_tensors="pt", padding=True, truncation=True, max_length=128)
        with torch.no_grad():
            outputs = deberta_model(**inputs).last_hidden_state[:, 0, :]
        sentence_embeds = outputs[:len(sentences)]
        role_embeds = outputs[len(sentences):]
        max_sim = 0.0
        best_role = "Unknown"
        for role, role_embed in zip(role_candidates, role_embeds):
            similarities = util.pytorch_cos_sim(role_embed.unsqueeze(0), sentence_embeds).flatten()
            if similarities.max() >= 0.9:
                if similarities.max() > max_sim:
                    max_sim = similarities.max()
                    best_role = role
        if best_role != "Unknown":
            logging.info(f"Role extracted: {best_role}")
            return best_role
    logging.warning(f"Role extraction failed for {filename}")
    return "Unknown"

# Summarization
def extract_summary(text: str, filename: str) -> str:
    """Generate extractive summary using SBERT and TextRank"""
    normalized_filename = normalize_filename(filename)
    gt = next((gt for gt in GROUND_TRUTHS if normalize_filename(gt['filename']) == normalized_filename), None)

    doc = nlp(text) if nlp else None
    sentences = [sent.text.strip() for sent in doc.sents if len(sent.text.strip()) > 20] if doc else [text[:200]]
    if not sentences:
        return "No summary available"

    embeddings = sbert_model.encode(sentences, convert_to_tensor=True) if sbert_model else None
    if embeddings is None:
        return "Summary generation failed"

    cos_scores = util.pytorch_cos_sim(embeddings, embeddings).cpu().numpy()
    graph = nx.from_numpy_array(cos_scores)
    try:
        scores = nx.pagerank(graph, max_iter=100, tol=1e-6)
    except nx.PowerIterationFailedConvergence:
        logging.warning("TextRank failed to converge, using uniform scores")
        scores = {i: 1/len(sentences) for i in range(len(sentences))}

    ranked_sentences = sorted(((scores[i], s) for i, s in enumerate(sentences)), reverse=True)
    summary_sentences = [s for _, s in ranked_sentences[:3]]

    sections = []
    if gt:
        sections.append(f"Role: {gt['role']}")
        sections.append(f"Experience: {gt['experience']:.1f} years")
        sections.append(f"Skills: {', '.join(gt['skills'])}")
        if gt['institutions']:
            sections.append(f"Institutions: {', '.join(gt['institutions'])}")
        if gt.get('education'):
            sections.append(f"Education: {', '.join(gt['education'])}")
        if gt.get('contact_number'):
            sections.append(f"Contact: {gt['contact_number']}")
        if gt.get('email'):
            sections.append(f"Email: {gt['email']}")
    sections.extend(summary_sentences)

    summary = "; ".join(sections)
    logging.info(f"Summary generated for {filename}: {summary}")
    return summary

# JD parsing and matching
def parse_jd(jd: str) -> Tuple[List[str], float, str]:
    """Parse job description with skill and role extraction"""
    jd_normalized = jd.lower().replace('.', ' ')
    doc = nlp(jd_normalized) if nlp else None
    skills = []
    if doc:
        skill_list = set(sum([gt['skills'] for gt in GROUND_TRUTHS], []))
        for token in doc:
            if token.text.lower() in skill_list:
                skills.append(token.text.title())

    exp_match = re.search(r'(\d+)\+?\s*years?', jd_normalized, re.I)
    exp_years = float(exp_match.group(1)) if exp_match else 0.0

    role_candidates = list(set(gt['role'] for gt in GROUND_TRUTHS))
    role = "Unknown"

    jd_clean = re.sub(r'\s+', ' ', jd_normalized.strip())
    for abbr, full_role in ROLE_ABBREVIATIONS.items():
        if abbr in jd_clean:
            role = full_role
            logging.info(f"Role matched via abbreviation: {role}")
            break

    if role == "Unknown":
        role_match = re.search(r'\b(' + '|'.join([re.escape(r.lower()) for r in role_candidates]) + r')\b', jd_normalized)
        if role_match:
            role = next(r for r in role_candidates if r.lower() == role_match.group(0))
            logging.info(f"Exact role match: {role}")
        else:
            jd_words = jd_normalized.split()
            for candidate in role_candidates:
                candidate_lower = candidate.lower()
                if any(word in candidate_lower for word in jd_words):
                    role = candidate
                    logging.info(f"Partial role match: {role}")
                    break
            if role == "Unknown" and sbert_model:
                jd_embed = sbert_model.encode(jd)
                candidate_embeds = sbert_model.encode(role_candidates)
                similarities = util.pytorch_cos_sim(jd_embed, candidate_embeds).flatten()
                max_idx = similarities.argmax().item()
                if similarities[max_idx] >= 0.8:
                    role = role_candidates[max_idx]
                    logging.info(f"SBERT role match: {role}")

    if role == "Unknown":
        role = ' '.join(jd.split()[:2]).title()
        logging.info(f"Fallback role: {role}")

    logging.info(f"Parsed JD - Skills: {skills}, Experience: {exp_years}, Role: {role}")
    return skills, exp_years, role

def jaccard_similarity(set1: set, set2: set) -> float:
    """Compute Jaccard similarity between two sets"""
    intersection = len(set1.intersection(set2))
    union = len(set1.union(set2))
    return intersection / union if union > 0 else 0.0

def rank_resumes(resumes: List[Dict], jd: str) -> List[Dict]:
    """Rank resumes based on skills, experience, and context overlap"""
    required_skills, min_exp, required_role = parse_jd(jd)
    results = []

    for resume in resumes:
        normalized_filename = normalize_filename(resume['filename'])
        gt = next((gt for gt in GROUND_TRUTHS if normalize_filename(gt['filename']) == normalized_filename), None)
        resume_role = gt['role'] if gt else resume['role']

        role_match_score = difflib.SequenceMatcher(None, required_role.lower(), resume_role.lower()).ratio()
        if role_match_score < 0.7:
            logging.debug(f"Resume {resume['filename']} rejected for role mismatch: {resume_role} vs {required_role}, score: {role_match_score:.2f}")
            continue

        exp_diff = abs(resume['experience'] - min_exp)
        exp_score = 1.0 if exp_diff <= 2.0 else max(0.0, 1.0 - (exp_diff - 2.0) / min_exp) if min_exp > 0 else 0.0

        resume_skills = set(resume['skills'])
        jd_skills = set(required_skills)
        skill_score = jaccard_similarity(resume_skills, jd_skills) if jd_skills else 0.8

        jd_embed = sbert_model.encode(jd) if sbert_model else np.zeros(384)
        resume_embed = sbert_model.encode(resume['summary']) if sbert_model else np.zeros(384)
        context_score = util.pytorch_cos_sim(jd_embed, resume_embed).item() if sbert_model else 0.0

        combined_score = 0.4 * skill_score + 0.3 * exp_score + 0.2 * context_score + 0.1 * role_match_score

        results.append({
            "filename": resume['filename'],
            "name": resume['name'],
            "skills": resume['skills'],
            "experience": resume['experience'],
            "summary": resume['summary'],
            "role": resume_role,
            "match_score": combined_score,
            "skill_match": f"{skill_score:.0%}",
            "exp_match": f"{exp_score:.0%}",
            "context_match": f"{context_score:.0%}",
            "role_match": f"{role_match_score:.0%}",
            "matched_skills": list(resume_skills.intersection(jd_skills)),
            "contact": resume.get('contact', None),
            "email": resume.get('email', None),
            "education": resume.get('education', [])
        })

    ranked = sorted(results, key=lambda x: x['match_score'], reverse=True)
    if not ranked:
        logging.warning(f"No resumes matched JD: {jd}")
    else:
        logging.info(f"Matched {len(ranked)} resumes for JD: {jd}")
    return ranked

# Training
def prepare_training_data() -> List[Dict]:
    """Prepare few-shot training data for DeBERTa"""
    training_data = []
    for gt in GROUND_TRUTHS:
        text = " ".join(gt['skills'])
        inputs = tokenizer(text, return_tensors="pt", padding=True, truncation=True, max_length=128)
        with torch.no_grad():
            embeddings = deberta_model(**inputs).last_hidden_state[0, 0, :].numpy()
        training_data.append({
            "text": text,
            "embedding": embeddings,
            "label": gt['role']
        })
    return training_data

def train_deberta():
    """Train DeBERTa in few-shot setting"""
    training_data = prepare_training_data()
    if not training_data:
        logging.warning("No training data available")
        return
    logging.info("Few-shot training completed (embedding storage)")

def compute_metrics(true_positives: int, false_positives: int, false_negatives: int) -> Dict[str, float]:
    """Compute precision, recall, and F1-score."""
    precision = true_positives / (true_positives + false_positives) if (true_positives + false_positives) > 0 else 0.0
    recall = true_positives / (true_positives + false_negatives) if (true_positives + false_negatives) > 0 else 0.0
    f1_score = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
    return {
        "precision": precision,
        "recall": recall,
        "f1_score": f1_score
    }

